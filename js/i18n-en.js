(function () {
    var currentLang = 'es';

    function detectInitialLang() {
        var saved = null;
        try { saved = localStorage.getItem('laislabtc_lang'); } catch (e) { saved = null; }
        if (saved === 'es' || saved === 'en') return saved;
        var nav = (navigator.language || 'es').toLowerCase();
        return nav.indexOf('en') === 0 ? 'en' : 'es';
    }

    function getLang() {
        return currentLang;
    }

    function applyTranslations() {
        document.documentElement.lang = currentLang;
        var nodes = document.querySelectorAll('[data-i18n]');
        for (var i = 0; i < nodes.length; i++) {
            var el = nodes[i];
            var key = el.getAttribute('data-i18n');
            if (currentLang === 'en') {
                if (el.dataset.original === undefined) el.dataset.original = el.textContent;
                var t = window.EN[key];
                if (t !== undefined) el.textContent = t;
            } else if (el.dataset.original !== undefined) {
                el.textContent = el.dataset.original;
            }
        }
        var ariaNodes = document.querySelectorAll('[data-i18n-aria]');
        for (var j = 0; j < ariaNodes.length; j++) {
            var ael = ariaNodes[j];
            var akey = ael.getAttribute('data-i18n-aria');
            if (currentLang === 'en') {
                if (ael.dataset.originalAria === undefined) ael.dataset.originalAria = ael.getAttribute('aria-label') || '';
                var ta = window.EN[akey];
                if (ta !== undefined) ael.setAttribute('aria-label', ta);
            } else if (ael.dataset.originalAria !== undefined) {
                ael.setAttribute('aria-label', ael.dataset.originalAria);
            }
        }
        if (currentLang === 'en') {
            document.title = window.EN['meta.title'];
            var md = document.querySelector('meta[name="description"]');
            if (md) md.setAttribute('content', window.EN['meta.description']);
            var ml = document.querySelector('meta[name="language"]');
            if (ml) ml.setAttribute('content', 'en');
        } else {
            document.title = "La IslaBTC - Comunidad Bitcoin en La Isla de la Juventud | Educación y Eventos Bitcoin";
            var md2 = document.querySelector('meta[name="description"]');
            if (md2) md2.setAttribute('content', "La IslaBTC - Comunidad Bitcoin en La Isla de la Juventud. Educación gratuita sobre Bitcoin, cursos presenciales, eventos y promoción de la economía circular con Bitcoin en Cuba.");
            var ml2 = document.querySelector('meta[name="language"]');
            if (ml2) ml2.setAttribute('content', 'es');
        }
        var langSel = document.getElementById('langSel');
        if (langSel) langSel.textContent = currentLang === 'en' ? 'EN' : 'ES';
        var langLabel = document.getElementById('langLabel');
        if (langLabel) langLabel.textContent = currentLang === 'en' ? 'English' : 'Español';
        document.dispatchEvent(new CustomEvent('langchange', { detail: { lang: currentLang } }));
    }

    function setLang(lang) {
        if (lang !== 'es' && lang !== 'en') return;
        currentLang = lang;
        try { localStorage.setItem('laislabtc_lang', lang); } catch (e) { /* ignore */ }
        applyTranslations();
    }

    window.getLang = getLang;
    window.setLang = setLang;

    currentLang = detectInitialLang();

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', applyTranslations);
    } else {
        applyTranslations();
    }
})();